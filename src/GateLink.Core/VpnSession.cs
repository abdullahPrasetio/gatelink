using GateLink.Core.Vault;

namespace GateLink.Core;

public enum VpnPhase
{
    Idle,
    Authenticating,
    Connecting,
    Connected,
    Reconnecting,
    Disconnecting,
    Failed,
}

/// <summary>
/// Orchestrates the full connection lifecycle: authenticate (2FA) -> obtain
/// cookie -> start tunnel -> monitor health -> auto-reconnect. This mirrors the
/// responsibilities of the macOS VPNSession type (phase, connect, disconnect,
/// autoReconnect, checkHealth, reconnectAttempts).
/// </summary>
public sealed class VpnSession : IAsyncDisposable
{
    private readonly VpnEnvironment _env;
    private readonly OpenConnectRunner _runner;
    private readonly GlobalProtectAuthenticator _auth;

    private GpCookie? _lastCookie;
    private string? _lastUser;
    private CancellationTokenSource? _healthCts;

    public VpnPhase Phase { get; private set; } = VpnPhase.Idle;
    public int ReconnectAttempts { get; private set; }
    public string Gateway => VpnConfig.Gateway;

    public event EventHandler<VpnPhase>? PhaseChanged;
    public event EventHandler<string>? Log;

    public VpnSession()
    {
        _env = new VpnEnvironment();
        _runner = new OpenConnectRunner(_env);
        _auth = new GlobalProtectAuthenticator(_runner);

        _runner.OutputReceived += (_, line) => Log?.Invoke(this, line);
        _runner.Exited += OnTunnelExited;
    }

    public bool IsEnvironmentReady => _env.IsReady;

    /// <summary>
    /// Detects a tunnel that is still running from a previous session (e.g. the
    /// app was quit while connected — openconnect keeps running as root). If the
    /// pid in the pid-file is alive, we adopt it and show Connected instead of
    /// a stale "Not connected". Call this once at startup.
    /// </summary>
    public void AdoptExistingTunnel()
    {
        try
        {
            if (!File.Exists(_env.PidPath)) return;
            var pidText = File.ReadAllText(_env.PidPath).Trim();
            if (!int.TryParse(pidText, out var pid) || pid <= 0) return;

            if (IsProcessAlive(pid))
            {
                Log?.Invoke(this, $"Adopted existing tunnel (pid {pid}).");
                Transition(VpnPhase.Connected);
                StartHealthMonitor();
            }
        }
        catch
        {
            // best effort — if detection fails, we just show the normal state
        }
    }

    private static bool IsProcessAlive(int pid)
    {
        try
        {
            using var p = System.Diagnostics.Process.GetProcessById(pid);
            return !p.HasExited;
        }
        catch
        {
            return false;   // no such process
        }
    }

    private bool IsPidFileAlive()
    {
        try
        {
            if (!File.Exists(_env.PidPath)) return false;
            var txt = File.ReadAllText(_env.PidPath).Trim();
            return int.TryParse(txt, out var pid) && pid > 0 && IsProcessAlive(pid);
        }
        catch { return false; }
    }

    /// <summary>
    /// One-tap connect using a stored vault entry. The OTP is generated by the
    /// app (no manual entry), and the username/password come from the entry.
    /// Unlocking the vault (Touch ID / Windows Hello) happens through
    /// <paramref name="vault"/>, matching MantraVPN: one unlock serves connect
    /// and reveal/copy until auto-relock.
    /// </summary>
    public async Task ConnectWithVaultAsync(OtpVault vault, VaultEntry entry, CancellationToken ct = default)
    {
        // A single unlock gate guards access to both the password and the OTP.
        if (!await vault.EnsureUnlockedAsync($"Connect to {Gateway}", ct))
            throw new InvalidOperationException("Unlock cancelled. VPN not connected.");

        var username = entry.VpnUsername
                       ?? throw new InvalidOperationException("No VPN username stored for this account.");
        var password = entry.VpnPassword
                       ?? throw new InvalidOperationException("No VPN password stored for this account.");
        var otp = entry.CreateGenerator().Generate();

        await ConnectAsync(username, password, otp, ct);
    }

    /// <summary>
    /// Full connect flow. Credentials are used only for the authenticate phase
    /// and are not persisted by this type.
    /// </summary>
    public async Task ConnectAsync(string username, string password, string otp, CancellationToken ct = default)
    {
        if (!_env.IsReady)
        {
            Transition(VpnPhase.Failed);
            throw new InvalidOperationException(
                "openconnect not found. Install OpenConnect for Windows and ensure it is on PATH.");
        }

        _lastUser = username;
        ReconnectAttempts = 0;

        Transition(VpnPhase.Authenticating);
        _lastCookie = await _auth.AuthenticateAsync(username, password, otp, ct);

        Transition(VpnPhase.Connecting);
        _runner.StartTunnel(_lastCookie);

        Transition(VpnPhase.Connected);
        StartHealthMonitor();
    }

    public async Task DisconnectAsync()
    {
        Transition(VpnPhase.Disconnecting);
        StopHealthMonitor();
        await _runner.StopAsync();
        _lastCookie = null;
        Transition(VpnPhase.Idle);
    }

    private void OnTunnelExited(object? sender, int exitCode)
    {
        Log?.Invoke(this, $"Tunnel exited with code {exitCode}.");
        if (Phase is VpnPhase.Disconnecting or VpnPhase.Idle) return;

        // Unexpected drop: attempt auto-reconnect using the last cookie.
        // Guard the fire-and-forget task so a failure can never crash the app.
        _ = Task.Run(async () =>
        {
            try { await AutoReconnectAsync(); }
            catch (Exception ex) { Log?.Invoke(this, $"Reconnect error: {ex.Message}"); }
        });
    }

    /// <summary>
    /// Re-establishes the tunnel after an unexpected drop, up to
    /// <see cref="VpnConfig.MaxReconnectAttempts"/>. Reuses the existing cookie;
    /// if it has expired, a full re-authentication is required by the user.
    /// </summary>
    private async Task AutoReconnectAsync()
    {
        if (_lastCookie is null) { Transition(VpnPhase.Failed); return; }

        while (ReconnectAttempts < VpnConfig.MaxReconnectAttempts)
        {
            ReconnectAttempts++;
            Transition(VpnPhase.Reconnecting);
            Log?.Invoke(this, $"Auto-reconnect attempt {ReconnectAttempts}/{VpnConfig.MaxReconnectAttempts}...");

            try
            {
                await Task.Delay(TimeSpan.FromSeconds(2 * ReconnectAttempts));
                _runner.StartTunnel(_lastCookie);
                Transition(VpnPhase.Connected);
                StartHealthMonitor();
                return;
            }
            catch (Exception ex)
            {
                Log?.Invoke(this, $"Reconnect failed: {ex.Message}");
            }
        }

        Transition(VpnPhase.Failed);
    }

    private void StartHealthMonitor()
    {
        StopHealthMonitor();
        _healthCts = new CancellationTokenSource();
        var token = _healthCts.Token;
        _ = Task.Run(async () =>
        {
            try
            {
                while (!token.IsCancellationRequested)
                {
                    await Task.Delay(VpnConfig.HealthCheckInterval, token);
                    // The tunnel is alive if either the process we started is
                    // running, or (for an adopted tunnel) the pid-file process
                    // is still alive.
                    if (!_runner.IsRunning && !IsPidFileAlive() && Phase == VpnPhase.Connected)
                    {
                        Log?.Invoke(this, "Health check: tunnel process is not running.");
                        OnTunnelExited(this, -1);
                        return;
                    }
                }
            }
            catch (OperationCanceledException)
            {
                // Normal on disconnect/dispose — not an error.
            }
            catch (Exception ex)
            {
                // Never let a background exception abort the process.
                Log?.Invoke(this, $"Health monitor error: {ex.Message}");
            }
        }, token);
    }

    private void StopHealthMonitor()
    {
        _healthCts?.Cancel();
        _healthCts?.Dispose();
        _healthCts = null;
    }

    private void Transition(VpnPhase next)
    {
        Phase = next;
        PhaseChanged?.Invoke(this, next);
    }

    public async ValueTask DisposeAsync()
    {
        StopHealthMonitor();
        await _runner.DisposeAsync();
    }
}
